-- Biodiversity Species Explorer: Supabase setup
-- Run this in Supabase Dashboard > SQL Editor > New query > Run.

create table if not exists public.species (
  id bigint generated by default as identity primary key,
  common_name text not null,
  scientific_name text,
  category text,
  conservation_status text,
  location text,
  description text,
  image_url text,
  created_at timestamptz default now()
);

alter table public.species enable row level security;
grant select on table public.species to anon, authenticated;
grant insert, update, delete on table public.species to authenticated;
grant usage, select on sequence public.species_id_seq to authenticated;

-- Anyone can browse the species catalog.
drop policy if exists "Public can view species" on public.species;
create policy "Public can view species" on public.species
for select to anon, authenticated using (true);

-- Only signed-in Supabase users can manage species.
drop policy if exists "Signed-in users can add species" on public.species;
create policy "Signed-in users can add species" on public.species
for insert to authenticated with check (true);

drop policy if exists "Signed-in users can edit species" on public.species;
create policy "Signed-in users can edit species" on public.species
for update to authenticated using (true) with check (true);

drop policy if exists "Signed-in users can delete species" on public.species;
create policy "Signed-in users can delete species" on public.species
for delete to authenticated using (true);

