-- Storage policies for the species-images bucket.
grant select, insert, update, delete on storage.objects to anon, authenticated;
drop policy if exists "public_read_species_images" on storage.objects;
drop policy if exists "Public can view species images" on storage.objects;
create policy "Public can view species images" on storage.objects
for select to anon, authenticated using (bucket_id = 'species-images');

drop policy if exists "Signed-in users can upload species images" on storage.objects;
create policy "Signed-in users can upload species images" on storage.objects
for insert to authenticated with check (bucket_id = 'species-images');

drop policy if exists "Signed-in users can update species images" on storage.objects;
create policy "Signed-in users can update species images" on storage.objects
for update to authenticated using (bucket_id = 'species-images') with check (bucket_id = 'species-images');

drop policy if exists "Signed-in users can delete species images" on storage.objects;
create policy "Signed-in users can delete species images" on storage.objects
for delete to authenticated using (bucket_id = 'species-images');
